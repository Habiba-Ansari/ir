# Logical Operations
a = True
b = False

print("Logical Operations:")
print("a AND b =", a and b)
print("a OR b =", a or b)
print("NOT a =", not a)

# Bitwise Operations
x = 5   # 101 in binary
y = 3   # 011 in binary

print("\nBitwise Operations:")
print("x & y =", x & y)
print("x | y =", x | y)
print("x ^ y =", x ^ y)
print("~x =", ~x)
